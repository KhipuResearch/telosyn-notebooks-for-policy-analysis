#!/usr/bin/env python3
"""Generate each project's README.md and docs/project-index.md from the notebooks.

A project README here is derived, never hand-written: title, thesis, learning
objectives, sources and limitations are read from the notebook's own markdown
and from the provenance records committed beside it. If the notebook changes,
rerun this and the README follows. `tests/test_project_readmes.py` fails when
a README has drifted from what this script would produce.

Usage::

    python scripts/build_project_readmes.py          # write
    python scripts/build_project_readmes.py --check  # exit 1 if any README is stale

SPDX-License-Identifier: LicenseRef-Proprietary
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
PROJECTS = REPO_ROOT / "projects"

SECTION_TITLES = {
    "01-fundamentals": "Fundamentals",
    "02-health-housing": "Health and Housing",
    "03-inequality-demographics": "Inequality and Demographics",
    "04-economy-industry": "Economy and Industry",
    "05-social-systems": "Social Systems",
    "06-infrastructure-environment": "Infrastructure and Environment",
    "07-justice-equity": "Justice and Equity",
    "08-culture-society": "Culture and Society",
    # The expansion (DECISIONS/0009). Project 12 is designed and held to the next
    # release; its title is here so that the folder can be added without touching
    # this file again.
    "09-causal-identification": "Causal Identification",
    "10-economic-evaluation": "Economic Evaluation",
    "11-distribution-heterogeneity": "Distribution and Heterogeneity",
    "12-simulation-foresight": "Simulation and Foresight",
    "13-evidence-synthesis": "Evidence Synthesis",
    "14-implementation": "Implementation and Take-up",
}

#: The eighteen publishers the corpus draws on, as a reader would name them.
KNOWN_SOURCES: list[tuple[str, str]] = [
    ("Census ACS", r"American Community Survey|\bACS\b"),
    ("BLS LAUS", r"\bLAUS\b|Local Area Unemployment"),
    ("BLS QCEW", r"\bQCEW\b|Quarterly Census of Employment"),
    ("Census CBP", r"County Business Patterns|\bCBP\b"),
    ("Census BDS", r"Business Dynamics Statistics|\bBDS\b"),
    ("BEA", r"Bureau of Economic Analysis|\bBEA\b|ACPSA"),
    ("FRED / ALFRED", r"\bFRED\b|ALFRED"),
    ("HUD FMR", r"Fair Market Rent|\bFMR\b"),
    ("HUD CHAS", r"\bCHAS\b|Comprehensive Housing Affordability"),
    ("CDC PLACES", r"\bPLACES\b"),
    ("CDC NCHS", r"\bNCHS\b|National Center for Health Statistics"),
    ("EPA TRI", r"Toxics Release Inventory|\bTRI\b"),
    ("FBI CDE", r"Crime Data Explorer|\bCDE\b|\bUCR\b|NIBRS"),
    ("IRS BMF", r"Business Master File|\bBMF\b"),
    ("USDA ERS", r"Food Environment Atlas|\bERS\b|Economic Research Service"),
    ("Opportunity Atlas", r"Opportunity Atlas"),
    ("Social Capital Atlas", r"Social Capital Atlas"),
    ("MIT Election Lab", r"MIT Election"),
    ("Zillow", r"Zillow|\bZHVI\b|\bZORI\b"),
]

HEADER = "<!--\n© 2026 Deloatch, Williams, Faison & Parker, LLLP. All rights reserved.\nSPDX-License-Identifier: LicenseRef-Proprietary\nGenerated by scripts/build_project_readmes.py — edit the notebooks, not this file.\n-->\n"


def _md_cells(nb: Path) -> list[str]:
    cells = json.loads(nb.read_text(encoding="utf-8"))["cells"]
    return ["".join(c["source"]) for c in cells if c["cell_type"] == "markdown"]


def _section(md: list[str], *names: str) -> str:
    """Body of the first `## <name>` section among the names given."""
    text = "\n".join(md)
    for name in names:
        m = re.search(rf"^## {re.escape(name)}\s*\n(.*?)(?=^## |\Z)", text, re.S | re.M)
        if m:
            return m.group(1).strip()
    return ""


def _bullets(body: str, limit: int = 4) -> list[str]:
    """List items, with wrapped continuation lines joined back onto their item."""
    out: list[str] = []
    for line in body.splitlines():
        s = line.strip()
        if not s:
            continue
        if re.match(r"^(?:[-*]|\d+\.)\s+", s):
            out.append(re.sub(r"^(?:[-*]|\d+\.)\s+", "", s))
        elif out and line.startswith((" ", "\t")):
            out[-1] = out[-1].rstrip() + " " + s
        elif out and not s.startswith("#"):
            # an unindented wrap line belongs to the previous item too
            out[-1] = out[-1].rstrip() + " " + s
    out = [re.sub(r"\*\*(.+?)\*\*", r"\1", o).strip() for o in out]
    return out[:limit]


def _title_and_thesis(md: list[str], fallback: str) -> tuple[str, str]:
    for m in md:
        for line in m.splitlines():
            if line.startswith("# "):
                t = line[2:].strip()
                if " — " in t:
                    a, b = t.split(" — ", 1)
                    return a.strip(), b.strip()
                return t, ""
    return fallback, ""


def _sources(nb: Path, md: list[str]) -> list[str]:
    seen: list[str] = []
    for p in sorted((nb.parent / "provenance").glob("*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        for r in d if isinstance(d, list) else [d]:
            if isinstance(r, dict):
                s = r.get("source") or r.get("publisher") or r.get("dataset")
                if s and s not in seen:
                    seen.append(s)
    if not seen:
        # No committed provenance record (the notebook pins a local file or an
        # in-notebook digest instead): name the publishers the text identifies.
        text = "\n".join(md)
        for label, pattern in KNOWN_SOURCES:
            if re.search(pattern, text, re.I):
                seen.append(label)
    return seen


def describe(nb: Path) -> dict:
    md = _md_cells(nb)
    title, thesis = _title_and_thesis(md, nb.stem)
    return {
        "path": nb,
        "title": title,
        "thesis": thesis,
        "objectives": _bullets(_section(md, "Learning Objectives")),
        "sources": _sources(nb, md),
        "limitations": _bullets(_section(md, "Limitations", "Limits", "What this cannot show"), 3),
        "provenance_records": len(list((nb.parent / "provenance").glob("*.json"))),
    }


def _sections() -> list[Path]:
    """Project folders that hold at least one notebook, in order.

    A folder with no notebook has nothing to describe, so it gets no README and
    is not counted as a project. That lets an expansion project's folder exist
    before its first notebook without the generators claiming otherwise.
    """
    return sorted(p for p in PROJECTS.iterdir() if p.is_dir() and any(p.rglob("*.ipynb")))


def _title(section: Path) -> str:
    try:
        return SECTION_TITLES[section.name]
    except KeyError:
        raise ValueError(
            f"projects/{section.name} holds notebooks but has no entry in SECTION_TITLES "
            "(scripts/build_project_readmes.py); add its title there."
        ) from None


def render_project(section: Path) -> str:
    nbs = sorted(section.rglob("*.ipynb"))
    num, _slug = section.name.split("-", 1)
    out = [HEADER, f"# {num}. {_title(section)}\n"]
    out.append(f"{len(nbs)} notebook{'s' if len(nbs) != 1 else ''}. Each one is built on a live public "
               "source and holds a single methodological lesson about what that source permits a "
               "reader to conclude. Run any of them from the repository root:\n")
    out.append("```bash\npip install -e '.[notebooks]'\nexport KRL_SECRETS_PATH=<operator-path>/tutorials.env   # your own keys; see docs/reproducibility.md\n"
               f"jupyter lab projects/{section.name}/\n```\n")
    out.append("| Notebook | Thesis | Sources |\n|---|---|---|")
    for d in (describe(nb) for nb in nbs):
        rel = d["path"].relative_to(section)
        src = ", ".join(d["sources"][:3]) + (" …" if len(d["sources"]) > 3 else "")
        out.append(f"| [{d['title']}]({rel}) | {d['thesis']} | {src} |")
    out.append("")
    for d in (describe(nb) for nb in nbs):
        rel = d["path"].relative_to(section)
        out.append(f"## {d['title']}\n")
        if d["thesis"]:
            out.append(f"**{d['thesis']}.**\n")
        out.append(f"`{rel}`\n")
        if d["objectives"]:
            out.append("**What it shows**\n")
            out.extend(f"- {o}" for o in d["objectives"])
            out.append("")
        if d["sources"]:
            out.append("**Sources** — " + "; ".join(d["sources"]) +
                       (f"  \n{d['provenance_records']} provenance record{'s' if d['provenance_records'] != 1 else ''} committed in `{rel.parent}/provenance/`."
                        if d["provenance_records"] else "") + "\n")
        if d["limitations"]:
            out.append("**Limitations**\n")
            out.extend(f"- {l}" for l in d["limitations"])
            out.append("")
    out.append("---\n\nSee [`docs/methodology.md`](../../docs/methodology.md) for the data-source regimes these notebooks "
               "are built on, and [`docs/reproducibility.md`](../../docs/reproducibility.md) for what a re-run does and does not reproduce.\n")
    return "\n".join(out)


def render_index() -> str:
    out = [HEADER, "# Project index\n",
           "Every notebook in the corpus, by project. Thesis is the notebook's own title.\n",
           "| # | Project | Notebook | Thesis |\n|---|---|---|---|"]
    n = 0
    sections = _sections()
    for section in sections:
        for nb in sorted(section.rglob("*.ipynb")):
            n += 1
            d = describe(nb)
            rel = nb.relative_to(REPO_ROOT)
            out.append(f"| {n} | [{_title(section)}](../projects/{section.name}/README.md) | [{d['title']}](../{rel}) | {d['thesis']} |")
    out.append(f"\n{n} notebooks across {len(sections)} projects.\n")
    return "\n".join(out)


def main(check: bool) -> int:
    targets = {section / "README.md": render_project(section) for section in _sections()}
    targets[REPO_ROOT / "docs" / "project-index.md"] = render_index()
    stale = []
    for path, content in targets.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(str(path.relative_to(REPO_ROOT)))
        else:
            path.write_text(content, encoding="utf-8")
    if check:
        if stale:
            print("stale (rerun scripts/build_project_readmes.py):\n  " + "\n  ".join(stale))
            return 1
        print(f"{len(targets)} generated files are current")
        return 0
    print(f"wrote {len(targets)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
