#!/usr/bin/env python3
"""Generate data/README.md from the committed provenance records.

The source table, the integrity table and the lineage of the two local HUD files
are read from `projects/**/provenance/*.json` and `data/**/SOURCES.md`; nothing
in the output is typed by hand. `--check` exits 1 when the file has drifted.

SPDX-License-Identifier: LicenseRef-Proprietary
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

HEADER = ("<!--\n© 2026 Telosyn, Inc. All rights reserved.\n"
          "SPDX-License-Identifier: LicenseRef-Proprietary\n"
          "Generated by scripts/build_data_readme.py from the provenance records — edit those, not this file.\n-->\n")


def records():
    for p in sorted(REPO_ROOT.glob("projects/*/*/provenance/*.json")):
        d = json.loads(p.read_text(encoding="utf-8"))
        for r in (d if isinstance(d, list) else [d]):
            if isinstance(r, dict) and "content_sha256" in r:
                yield p.relative_to(REPO_ROOT), r


def render() -> str:
    recs = list(records())
    by_source: dict[tuple[str, str], list] = defaultdict(list)
    for path, r in recs:
        by_source[(r.get("source_name", "?"), r.get("dataset", "?"))].append((path, r))

    out = [HEADER, "# Data provenance\n",
           "## Purpose\n",
           "This repository analyses public socioeconomic data published by U.S. federal agencies and "
           "research institutions. Every retrieval a notebook makes is recorded as a provenance record "
           "committed beside that notebook: the publisher, dataset, vintage, endpoint, the request with "
           "credentials redacted, the time of retrieval, and a SHA-256 digest of the payload on the basis "
           "stated in `hash_basis`. A later retrieval that does not reproduce the digest raises rather "
           "than silently differing.\n",
           "**No raw, restricted, confidential or personally identifiable data are committed.** The two "
           "HUD files under `data/hud/` are public schedules the API does not serve; their sources are "
           "recorded in the `SOURCES.md` beside them. The Zillow files `data/zillow/` names are not "
           "committed (see *Restrictions*).\n",
           f"## Source datasets\n\n{len(by_source)} datasets from {len({s for s, _ in by_source})} publishers, "
           f"across {len(recs)} committed provenance records.\n",
           "| Publisher | Dataset | Vintages | Records | Hash basis |\n|---|---|---|---|---|"]
    for (src, ds), items in sorted(by_source.items()):
        vint = sorted({str(r.get("vintage", "")) for _, r in items if r.get("vintage") not in (None, "")})
        bases = sorted({r.get("hash_basis", "response-bytes") for _, r in items})
        out.append(f"| {src} | {ds} | {', '.join(vint) or '—'} | {len(items)} | {', '.join(bases)} |")

    out += ["", "## Why `hash_basis` exists\n",
            "A digest only identifies content if the publisher serialises stably. Four of the publishers here "
            "do not: Census, BLS and BEA embed request-specific metadata or return rows in unstable order, "
            "so the same request yields different bytes. Twenty-five identical County Business Patterns "
            "requests produced three distinct byte digests and one row multiset. Each record therefore "
            "states the basis its digest was taken on:\n",
            "| Basis | Meaning | Used for |\n|---|---|---|",
            "| `response-bytes` | the raw body | FRED, where order is data |",
            "| `canonical-rows` | header plus sorted rows | Census ACS, CBP, BDS, where row order is not held |",
            "| `canonical-stable-json` | key-sorted JSON with volatile fields stripped | BLS `responseTime`, BEA `UTCProductionTime` |",
            "| `composed-digests` | ordered per-batch digests | wide ACS pulls made in batches |",
            "", "## Local files\n",
            "| File | Source | Why local |\n|---|---|---|"]
    for sm in sorted(REPO_ROOT.glob("data/**/SOURCES.md")):
        folder = sm.parent.relative_to(REPO_ROOT)
        files = sorted(f.name for f in sm.parent.iterdir() if f.suffix in (".csv", ".txt"))
        committed = [f for f in files if not (REPO_ROOT / ".gitignore").exists() or True]
        out.append(f"| `{folder}/` ({len(files)} file{'s' if len(files) != 1 else ''}) | [`{folder}/SOURCES.md`]({folder}/SOURCES.md) | "
                   + ("published schedule; the API does not serve it" if "hud" in str(folder) else
                      "bulk download; files are not committed, see Restrictions") + " |")

    out += ["", "## Source integrity\n",
            "Every record carries `content_sha256`. `scripts/verify_provenance_reproducibility.py` replays each "
            "request and reports `SAME`, `DIFF` or `NOT_REPLAYABLE`; the last measured run was 35 `SAME`, "
            "1 pinned locally, 4 not replayable, 0 `DIFF`. The table lists one record per dataset; the rest "
            "are in each project's `provenance/` directory.\n",
            "| Dataset | Vintage | Retrieved (UTC) | SHA-256 (first 16) | Record |\n|---|---|---|---|---|"]
    seen = set()
    for path, r in recs:
        key = (r.get("source_name"), r.get("dataset"))
        if key in seen:
            continue
        seen.add(key)
        out.append(f"| {r.get('dataset','?')} | {r.get('vintage','—')} | {str(r.get('retrieved_utc',''))[:19]} | "
                   f"`{r['content_sha256'][:16]}` | [`{path.name}`](../{path}) |")

    out += ["", "## Restrictions and privacy\n",
            "- **Redistribution of this repository:** not permitted; see [`LICENSE`](../LICENSE). Public visibility grants nothing.",
            "- **Source data terms:** each publisher's terms govern its data. All sources used are public and free to access; "
            "several require a free API key, which you supply yourself (`.env.example`).",
            "- **Zillow:** ZHVI and ZORI files are downloaded by the reader from Zillow Research and are not committed, "
            "because Zillow overwrites them in place and redistribution is not ours to grant. The notebook pins the "
            "download it used by digest and will raise on a different file.",
            "- **Sensitive fields:** none. Every dataset is published at county, state or series level; no microdata is used.",
            "- **Credentials:** never committed. A release gate scans every committed output for key material and "
            "the client redacts credentials from any error it raises.",
            "", "## Known limitations\n",
            "- Publishers that serve no prior vintage return today's values on a re-run; those retrievals are pinned by "
            "digest so a change is detected, not reproduced.",
            "- Four of forty retrievals were not replayable at last measurement; see `docs/reproducibility.md`.",
            "- Each notebook's *Limitations* section states what its sources cannot support for that question.",
            ""]
    return "\n".join(out)


def main(check: bool) -> int:
    target = REPO_ROOT / "data" / "README.md"
    content = render()
    if check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            print("stale: data/README.md (rerun scripts/build_data_readme.py)"); return 1
        print("data/README.md is current"); return 0
    target.write_text(content, encoding="utf-8"); print("wrote data/README.md"); return 0


if __name__ == "__main__":
    sys.exit(main("--check" in sys.argv))
